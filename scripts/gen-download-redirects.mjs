// Stable download links for welcome emails (parity plan P2-5).
//
// Writes dist/_redirects with one rule per lead magnet and language:
//   /dl/<lang>/<magnet>  ->  that magnet's PDF in that language   (302)
// so a single email template per language can deliver whichever file the subscriber
// chose, through the MailerLite merge tag: https://griotmoon.com/dl/fr/{$lead_magnet}
//
// Source of truth: the pdf map of each magnet in src/components/EmailSignup.tsx, the same
// registry the landing pages and the prerender guard read. The build fails if a magnet has
// no pdf line, a language is missing, or a target file does not exist in public/.
// Unknown or empty slugs fall back to the starter kit in that language, so a subscriber
// whose lead_magnet field is blank still receives a file instead of a 404.
// 302, not 301: browsers cache 301s, and a replaced PDF must reach people immediately.
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
export const LANGS = ['en', 'es', 'fr'];
export const FALLBACK_MAGNET = 'bilingual-starter-kit';

/** { slug: { en, es, fr } } parsed from the LEAD_MAGNETS registry. */
export function readPdfMap(src = readFileSync(path.join(ROOT, 'src/components/EmailSignup.tsx'), 'utf8')) {
  const block = src.slice(src.indexOf('const LEAD_MAGNETS'), src.indexOf('const DEFAULT_MAGNET'));
  const starts = [...block.matchAll(/^ {2}'([a-z0-9-]+)': \{/gm)];
  const out = {};
  starts.forEach((m, i) => {
    const body = block.slice(m.index, starts[i + 1]?.index ?? block.length);
    const pdf = /^ {4}pdf: \{([^}]*)\}/m.exec(body);
    out[m[1]] = pdf ? Object.fromEntries([...pdf[1].matchAll(/(en|es|fr): '([^']+)'/g)].map((x) => [x[1], x[2]])) : {};
  });
  return out;
}

/** Problems with the map (missing languages, missing files). Empty means valid. */
export function validate(map, publicDir = path.join(ROOT, 'public')) {
  const problems = [];
  if (!Object.keys(map).length) problems.push('no lead magnets found in EmailSignup.tsx');
  if (!map[FALLBACK_MAGNET]) problems.push(`fallback magnet "${FALLBACK_MAGNET}" is not registered`);
  for (const [slug, pdfs] of Object.entries(map)) {
    for (const lang of LANGS) {
      if (!pdfs[lang]) problems.push(`${slug}: no ${lang} pdf`);
      else if (!existsSync(path.join(publicDir, pdfs[lang]))) problems.push(`${slug}: ${lang} pdf ${pdfs[lang]} is not in public/`);
    }
  }
  return problems;
}

/** The _redirects text: exact rules first, then per-language and global fallbacks. */
export function buildRedirects(map) {
  const lines = ['# Generated by scripts/gen-download-redirects.mjs (P2-5). Do not edit.'];
  for (const [slug, pdfs] of Object.entries(map)) for (const lang of LANGS) lines.push(`/dl/${lang}/${slug}  ${pdfs[lang]}  302`);
  for (const lang of LANGS) lines.push(`/dl/${lang}/*  ${map[FALLBACK_MAGNET][lang]}  302`);
  lines.push(`/dl/*  ${map[FALLBACK_MAGNET].en}  302`);
  return lines.join('\n') + '\n';
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const map = readPdfMap();
  const problems = validate(map);
  if (problems.length) {
    console.error(`\nDownload links aborted:\n  ${problems.join('\n  ')}\n`);
    process.exit(1);
  }
  const dist = path.join(ROOT, 'dist');
  if (!existsSync(dist)) {
    console.error('Download links aborted: dist/ does not exist; run after vite build.');
    process.exit(1);
  }
  writeFileSync(path.join(dist, '_redirects'), buildRedirects(map));
  console.log(`Download links OK: ${Object.keys(map).length} magnets x ${LANGS.length} languages, plus fallbacks, in dist/_redirects.`);
}
